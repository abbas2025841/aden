// دالة للبحث الشامل
export function comprehensiveSearch(query: string): {
  health: HealthFacility[];
  locations: AdenLocation[];
  jobs: Job[];
  schools: School[];
  universities: University[];
  district?: string;
} {
  const lowerQuery = query.toLowerCase();
  
  // استخراج المنطقة من الاستعلام
  let district: string | undefined;
  for (const neighborhood of NEIGHBORHOODS) {
    if (lowerQuery.includes(neighborhood.toLowerCase())) {
      district = neighborhood;
      break;
    }
  }

  return {
    health: searchHealthFacilities(query, district),
    locations: searchLocations(query, district),
    jobs: searchJobs(query, district),
    schools: searchSchools(query, district),
    universities: searchUniversities(query, district),
    district
  };
}
